<?php

namespace Tests\Support\Authentication\Concerns;

use App\Models\Tenant;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use RuntimeException;

trait ManagesLandlordTestTenants
{
    /**
     * Tenant domains created during the current test.
     *
     * @var array<int, string>
     */
    private array $trackedLandlordTenantDomains = [];

    /**
     * Tenant databases created during the current test.
     *
     * @var array<int, string>
     */
    private array $trackedLandlordTenantDatabases = [];

    /**
     * Register a tenant for landlord authentication tests.
     *
     * @return array{
     *     tenant: Tenant,
     *     domain: string,
     *     token: string
     * }
     */
    protected function registerLandlordTestTenant(): array
    {
        $domain = sprintf(
            'test-landlord-%s',
            strtolower(Str::random(10))
        );

        $email = $domain.'@example.test';

        $this->trackedLandlordTenantDomains[] = $domain;

        $response = $this->postJson('/api/register', [
            'name' => 'Tenant Test Administrator',
            'email' => $email,
            'password' => 'password123',
            'password_confirmation' => 'password123',
            'tenant_name' => (
                'Landlord Authentication Test Laboratory'
            ),
            'tenant_domain' => $domain,
        ]);

        $response
            ->assertCreated()
            ->assertJsonPath(
                'tenant.domain',
                $domain
            )
            ->assertJsonPath(
                'guard',
                'tenant'
            );

        $tenant = Tenant::query()
            ->where('domain', $domain)
            ->firstOrFail();

        $this->trackedLandlordTenantDatabases[] = (
            $tenant->database
        );

        $token = $response->json('token');

        $this->assertIsString($token);
        $this->assertNotSame('', $token);

        $this->restoreLandlordContext();

        return [
            'tenant' => $tenant,
            'domain' => $domain,
            'token' => $token,
        ];
    }

    /**
     * Remove temporary tenants and databases.
     */
    protected function cleanupLandlordTestTenants(): void
    {
        $this->restoreLandlordContext();

        $databases = $this->trackedLandlordTenantDatabases;

        foreach (
            $this->trackedLandlordTenantDomains as $domain
        ) {
            $tenant = Tenant::query()
                ->where('domain', $domain)
                ->first();

            if ($tenant !== null) {
                $databases[] = $tenant->database;
                $tenant->delete();
            }
        }

        foreach (
            array_unique($databases) as $database
        ) {
            $this->dropLandlordTestTenantDatabase(
                $database
            );
        }

        $this->trackedLandlordTenantDomains = [];
        $this->trackedLandlordTenantDatabases = [];
    }

    /**
     * Drop only databases generated by automated tests.
     */
    private function dropLandlordTestTenantDatabase(
        string $database
    ): void {
        if (
            ! preg_match(
                '/^tenant_[a-z0-9_]+$/',
                $database
            )
            || ! str_contains($database, '_test_')
        ) {
            throw new RuntimeException(
                sprintf(
                    'Refusing to drop unsafe database [%s].',
                    $database
                )
            );
        }

        DB::connection('landlord')->statement(
            sprintf(
                'DROP DATABASE IF EXISTS `%s`',
                $database
            )
        );
    }
}